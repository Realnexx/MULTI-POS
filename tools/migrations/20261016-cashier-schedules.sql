CREATE TABLE IF NOT EXISTS cashier_schedule_policies (
 branch_id INT PRIMARY KEY, early_minutes SMALLINT UNSIGNED NOT NULL DEFAULT 0,
 late_minutes SMALLINT UNSIGNED NOT NULL DEFAULT 0, updated_by INT NOT NULL,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS cashier_schedules (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, branch_id INT NOT NULL, cashier_id INT NOT NULL,
 starts_at DATETIME NOT NULL, ends_at DATETIME NOT NULL, status ENUM('scheduled','cancelled') NOT NULL DEFAULT 'scheduled',
 notes VARCHAR(500) NOT NULL DEFAULT '', created_by INT NOT NULL, updated_by INT NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX(cashier_id,status,starts_at,ends_at), INDEX(branch_id,starts_at)
) ENGINE=InnoDB;
