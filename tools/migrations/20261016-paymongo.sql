CREATE TABLE IF NOT EXISTS paymongo_config (
 id TINYINT PRIMARY KEY, enabled TINYINT NOT NULL DEFAULT 0, mode VARCHAR(4) NOT NULL DEFAULT 'test',
 public_key VARCHAR(255) NOT NULL DEFAULT '', secret_cipher TEXT NOT NULL, webhook_cipher TEXT NOT NULL,
 site_url VARCHAR(512) NOT NULL DEFAULT '', synced_at DATETIME NULL, updated_by INT NULL,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS paymongo_methods (
 mode VARCHAR(4) NOT NULL, code VARCHAR(80) NOT NULL, label VARCHAR(100) NOT NULL,
 available TINYINT NOT NULL DEFAULT 1, synced_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(mode,code)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS paymongo_payments (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, order_id INT NOT NULL, branch_id INT NOT NULL,
 active_order_id INT NULL UNIQUE, session_id VARCHAR(100) NULL UNIQUE, payment_id VARCHAR(100) NULL UNIQUE,
 request_key CHAR(64) NOT NULL UNIQUE, amount_cents BIGINT NOT NULL, mode VARCHAR(4) NOT NULL,
 secret_cipher TEXT NOT NULL, webhook_cipher TEXT NOT NULL, request_payload LONGTEXT NOT NULL,
 checkout_url TEXT NULL, state VARCHAR(24) NOT NULL DEFAULT 'creating', method VARCHAR(80) NULL,
 sale_id INT NULL UNIQUE, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX(order_id,id),INDEX(branch_id,state)
) ENGINE=InnoDB;
